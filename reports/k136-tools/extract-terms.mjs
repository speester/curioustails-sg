#!/usr/bin/env node
// K-136: copy the buyer-facing reservation terms, word for word, out of the
// legal redline's clean-text appendix into src/data/reservation-terms.json.
//
//   node reports/k136-tools/extract-terms.mjs
//
// Only Part A (reservation terms) and Part B (delay clause) are copied. Part C
// is the takedown policy: C1 is a separate proposed page and C2 is an internal
// SOP that must never be published. Nothing is reworded; square-bracketed text
// is an open point with counsel and is kept as-is for the page to mark.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SRC = 'reports/imported-puppy-legal-redline-2026-11-11.md';
const md = readFileSync(path.join(ROOT, SRC), 'utf8');

const start = md.indexOf('# Appendix: clean text (all changes accepted)');
const end = md.indexOf('## Part C. Takedown policy', start);
if (start < 0 || end < 0) throw new Error('clean-text appendix or Part C heading not found');
const lines = md.slice(start, end).split(/\r?\n/).slice(1);

const parts = [];
let part = null;
let clause = null;
for (const raw of lines) {
  const line = raw.trim();
  if (!line) continue;
  let m;
  if ((m = /^## (Part [AB]\. .+)$/.exec(line))) {
    part = { title: m[1], clauses: [] };
    parts.push(part);
    clause = null;
  } else if ((m = /^\*\*([AB]\d+\. .+)\*\*$/.exec(line))) {
    clause = { heading: m[1], paras: [] };
    part.clauses.push(clause);
  } else if (clause) {
    clause.paras.push(line);
  } else {
    throw new Error(`unexpected line outside a clause: ${line.slice(0, 60)}`);
  }
}

const header = md.split(/\r?\n/).find((l) => l.startsWith('**Date:**')) ?? '';
const out = {
  _comment: `Generated by reports/k136-tools/extract-terms.mjs from ${SRC}. Do not edit by hand: change the redline, then re-run.`,
  source: SRC,
  header: header.replace(/\*\*/g, ''),
  status: 'draft-under-legal-review',
  parts,
};
writeFileSync(path.join(ROOT, 'src', 'data', 'reservation-terms.json'), JSON.stringify(out, null, 2) + '\n');
console.log(parts.map((p) => `${p.title}: ${p.clauses.length} clauses, ${p.clauses.reduce((n, c) => n + c.paras.length, 0)} paragraphs`).join('\n'));
