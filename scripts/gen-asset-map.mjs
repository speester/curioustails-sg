// public/images/asset-map.json — route -> feature image, for ArticleCard.
// Derived from each page's own declared ogImage, which is a real file under public/,
// so a card's picture is the same picture the page shows a sharer. Re-runnable.
import fs from 'node:fs';
import path from 'node:path';

const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.astro')) files.push(p);
  }
})('src/pages');

const map = {};
for (const f of files) {
  const s = fs.readFileSync(f, 'utf8');
  const m = s.match(/ogImage=["']([^"']+)["']/);
  if (!m) continue;
  const asset = m[1];
  if (!asset.startsWith('/') || !fs.existsSync(path.join('public', asset.replace(/^\//, '')))) continue;
  let route = '/' + path.relative('src/pages', f).split(String.fromCharCode(92)).join('/').replace(/\.astro$/, '');
  route = route.replace(/\/index$/, '') || '/';
  if (!route.endsWith('/')) route += '/';
  map[route] = { feature: asset };
}
const out = { _comment: 'GENERATED by scripts/gen-asset-map.mjs from each page’s declared ogImage. Do not hand-edit.', ...map };
fs.mkdirSync('public/images', { recursive: true });
fs.writeFileSync('public/images/asset-map.json', JSON.stringify(out, null, 2) + '\n');
console.log(`gen-asset-map: routes=${Object.keys(map).length}`);
