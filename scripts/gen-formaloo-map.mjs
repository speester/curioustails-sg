#!/usr/bin/env node
// kit:gen-formaloo-map@1.0.0 — src/data/forms.ts from every config/formaloo.<key>.json.
// Usage: node scripts/gen-formaloo-map.mjs --check | --write
import fs from 'node:fs';
import path from 'node:path';

// LEAD_CAPTURE says how this site takes an enquiry. A WhatsApp-first or phone-first
// business has no form by design, and hard-stopping it forever is a gate that can never
// go green on a correctly built site. `form` (default) keeps the original behaviour.
const LEAD_CAPTURE = (() => {
  try {
    const m = fs.readFileSync('config/project-config.md', 'utf8').match(/^LEAD_CAPTURE:(.*)$/m);
    if (m) {
      const v = m[1].split('#')[0].trim().toLowerCase();
      if (v) return v;
    }
  } catch { /* no config: assume a form, as before */ }
  return 'form';
})();
const FORMLESS = ['whatsapp', 'phone', 'none'].includes(LEAD_CAPTURE);

const write = process.argv.includes('--write');
const OUT = path.join('src', 'data', 'forms.ts');
const files = fs.existsSync('config') ? fs.readdirSync('config').filter((f) => /^formaloo\..+\.json$/.test(f)) : [];
if (FORMLESS) {
  console.log(`PASS no form by design - LEAD_CAPTURE: ${LEAD_CAPTURE}. Enquiries arrive`);
  console.log('     through that channel, so there is no config/formaloo.<key>.json to read.');
  process.exit(0);
}
if (!files.length) { console.error('FAIL no config/formaloo.<key>.json — run formaloo-forms (Stage 1.5) FIRST. astro-build HARD-STOPS here.'); process.exit(1); }

const PURPOSES = new Set(['consumer-lead', 'partner-pitch', 'order', 'newsletter']);
const forms = {}; const problems = [];
for (const f of files) {
  const c = JSON.parse(fs.readFileSync(path.join('config', f), 'utf8'));
  if (!c.key) problems.push(`${f}: missing key`);
  if (!PURPOSES.has(c.purpose)) problems.push(`${f}: purpose "${c.purpose}" is not one of ${[...PURPOSES].join('|')}`);
  if (!c.slug || !c.displayKey) problems.push(`${f}: FORM_SLUG and displayKey are required (the runtime path is the public display endpoint)`);
  const visible = (c.fields ?? []).filter((x) => !x.hidden && !x.tracking);
  if (visible.length > 6) problems.push(`${f}: ${visible.length} visible fields (CRO cap is 6)`);
  if (c.purpose === 'partner-pitch') {
    for (const bad of ['tcpa', 'emergency', '911']) if ((c.compliance ?? []).includes(bad)) problems.push(`${f}: partner-pitch form carries "${bad}" compliance copy — that is a liability on a B2B enquiry`);
    const site = (c.fields ?? []).find((x) => x.alias === 'site' || /site|website/i.test(x.title ?? ''));
    if (site && (site.type === 'url' || site.required)) problems.push(`${f}: the site field must be OPTIONAL short_text, never a URL-typed or required field`);
  }
  forms[c.key] = {
    key: c.key, purpose: c.purpose, slug: c.slug, displayKey: c.displayKey,
    function: c.function ?? `/api/${c.key}`, thankYou: c.thankYou ?? '/contact/thank-you/',
    // `form_submit` has NO EMITTER anywhere in the kit, so every partner-pitch,
    // order and newsletter form defaulted to a conversion that can never fire - and
    // launch then registered it as a GA4 key event. Derive from purpose, and refuse an
    // unknown purpose rather than emitting the dead name.
    ga4_event: c.ga4_event ?? ({
      'consumer-lead': 'generate_lead',
      'partner-pitch': 'partner_enquiry',
      'order': 'generate_lead',
      'newsletter': 'newsletter_signup',
    }[c.purpose] ?? (() => { throw new Error(`${f}: unknown purpose "${c.purpose}" - cannot derive a ga4_event, and form_submit has no emitter`); })()),
    notify_to: c.notify_to ?? '', honeypot: c.honeypot_field ?? 'company_website',
    submitLabel: c.submitLabel ?? (c.purpose === 'partner-pitch' ? 'Send enquiry' : 'Get help now'),
    compliance: c.compliance ?? [], fields: c.fields ?? [],
  };
}

const body = `// GENERATED by scripts/gen-formaloo-map.mjs — edit config/formaloo.<key>.json, never this file.
export interface FormField { alias: string; title: string; type: string; required?: boolean; hidden?: boolean; tracking?: boolean; help?: string; choices?: { slug: string; title: string }[]; }
export interface FormDef { key: string; purpose: 'consumer-lead'|'partner-pitch'|'order'|'newsletter'; slug: string; displayKey: string; function: string; thankYou: string; ga4_event: string; notify_to: string; honeypot: string; submitLabel: string; compliance: string[]; fields: FormField[]; }
export const FORMS: Record<string, FormDef> = ${JSON.stringify(forms, null, 2)};
export default FORMS;
`;
const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
const drift = existing.trim() !== body.trim();

console.log('CHECK              | RESULT');
console.log(`config files       | ${files.length}`);
console.log(`forms              | ${Object.keys(forms).length}`);
console.log(`problems           | ${problems.length ? `FAIL (${problems.length})` : 'PASS'}`);
for (const p of problems) console.log('   ' + p);
console.log(`src/data/forms.ts  | ${drift ? 'FAIL (stale)' : 'PASS'}`);
// --- functions/api/_formaloo-map.js -----------------------------------------------------
// kit fix 1.0.1: the contract says this file is compiled here, but 1.0.0 only ever wrote
// src/data/forms.ts. functions/api/inquiry.js imports { FORMS, HONEYPOT } from it, so without
// this block the deployed Pages Function fails to resolve its import and EVERY submit 500s.
// Shape is exactly what inquiry.js reads: required[], aliases[], choices{alias:{title:slug}},
// submit_url, success_url, notify_email.
{
  const fnForms = {};
  for (const [key, f] of Object.entries(forms)) {
    const cfg = JSON.parse(fs.readFileSync(path.join('config', `formaloo.${key}.json`), 'utf8'));
    const fields = cfg.fields ?? [];
    const choices = {};
    for (const fl of fields) {
      if (fl.choices?.length) {
        choices[fl.alias] = Object.fromEntries(fl.choices.map((c) => [c.title, c.slug]));
      }
    }
    fnForms[key] = {
      required: fields.filter((x) => x.required).map((x) => x.alias),
      aliases: fields.map((x) => x.alias),
      choices,
      submit_url: cfg.submit_url,
      success_url: f.thankYou,
      // A080 - a failing NEWSLETTER submit from the footer of a blog post used to 303 the
      // visitor to /contact/?error=... : a page they never asked for, on a form that has
      // nothing to do with contacting anyone. The failure lands back where the form IS.
      error_url: cfg.error_url ?? '',
      anchor: cfg.anchor ?? (f.purpose === 'newsletter' ? 'newsletter' : 'contact-form'),
      notify_email: f.notify_to,
      ga4_event: f.ga4_event,
    };
  }
  // A018 - the E.164 dial code is a PROJECT FACT. inquiry.js used to infer it from digit
  // count and stamped +1 on every ten-digit number, so an SG lead was captured as a US
  // one and nobody could call it back. Stage 1.5 writes `default_dial_code` into
  // config/formaloo.<key>.json (derived from COUNTRY); it is compiled through to the
  // Function here, and an absent code means inquiry.js never invents a country.
  const dial = (() => {
    for (const key of Object.keys(forms)) {
      const cfg = JSON.parse(fs.readFileSync(path.join('config', `formaloo.${key}.json`), 'utf8'));
      if (cfg.default_dial_code) return String(cfg.default_dial_code);
    }
    return '';
  })();
  if (!dial) console.log('NOTE default_dial_code absent from every config/formaloo.<key>.json — phone numbers will be stored as typed, with no country code inferred');

  const fnBody = `// GENERATED by scripts/gen-formaloo-map.mjs — edit config/formaloo.<key>.json, never this file.
`
    + `export const FORMS = ${JSON.stringify(fnForms, null, 2)};
`
    + `export const DEFAULT_DIAL_CODE = ${JSON.stringify(dial)};
`
    + `export const HONEYPOT = ${JSON.stringify(Object.values(forms)[0]?.honeypot ?? 'company_website')};
`
    + `export default FORMS;
`;
  const FN_OUT = path.join('functions', 'api', '_formaloo-map.js');
  const fnExisting = fs.existsSync(FN_OUT) ? fs.readFileSync(FN_OUT, 'utf8') : '';
  if (write) {
    fs.mkdirSync(path.dirname(FN_OUT), { recursive: true });
    fs.writeFileSync(FN_OUT, fnBody);
    console.log('PASS wrote', FN_OUT);
  } else if (fnExisting.trim() !== fnBody.trim()) {
    console.error('FAIL', FN_OUT, 'is stale — run with --write');
    process.exitCode = 1;
  }
}

if (write && !problems.length) { fs.mkdirSync(path.dirname(OUT), { recursive: true }); fs.writeFileSync(OUT, body, 'utf8'); console.log('\nPASS wrote ' + OUT); process.exit(0); }
console.log(problems.length || drift ? '\nFAIL gen-formaloo-map' : '\nPASS gen-formaloo-map');
process.exit(problems.length || drift ? 1 : 0);
