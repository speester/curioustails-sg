#!/usr/bin/env node
/**
 * gen-privacy-data-list.mjs — generate the privacy policy's "data we collect / who receives it /
 * retention" list from config/forms.json, so a field change propagates to /privacy/.
 *
 *   node scripts/gen-privacy-data-list.mjs           writes src/data/privacy-data.ts
 *   node scripts/gen-privacy-data-list.mjs --print   prints the same block (for diffing)
 */
import fs from 'node:fs';
const ex = p => { try { fs.accessSync(p); return true; } catch { return false; } };
if (!ex('config/forms.json')) { console.error('FAIL: config/forms.json missing.'); process.exit(1); }
const reg = JSON.parse(fs.readFileSync('config/forms.json', 'utf8'));
const LABEL = { full_name: 'your name', email: 'your email address', phone: 'your phone number', message: 'the message you write', site: 'your website address', topic: 'the topic you propose', budget_band: 'your budget band', page_url: 'the page you submitted from', utm_source: 'the campaign source', utm_medium: 'the campaign medium', utm_campaign: 'the campaign name' };
const items = [];
for (const f of reg.forms || []) {
  const fields = (f.fields || []).map(x => LABEL[x.alias] || x.title || x.alias);
  items.push({ form: f.id, purpose: f.purpose || f.type, collects: fields, recipients: f.recipients || ['our team by email', 'our form provider (Formaloo)'], retention: f.retention || '24 months' });
}
const block = `// GENERATED by scripts/gen-privacy-data-list.mjs from config/forms.json — DO NOT EDIT.
// data-we-collect
export const PRIVACY_DATA = ${JSON.stringify(items, null, 2)} as const;
// end
`;
if (process.argv.includes('--print')) { process.stdout.write(block); process.exit(0); }
fs.mkdirSync('src/data', { recursive: true });
fs.writeFileSync('src/data/privacy-data.ts', block, 'utf8');
console.log('form'.padEnd(16) + 'fields'.padEnd(10) + 'retention'.padEnd(14) + 'result');
console.log('-'.repeat(52));
for (const i of items) console.log(String(i.form).padEnd(16) + String(i.collects.length).padEnd(10) + String(i.retention).padEnd(14) + 'PASS');
console.log(`\nPRIVACY_DATA_OK forms=${items.length}`);
// contracts section-1b, generator form: a generator that wrote NOTHING has
// silently done nothing, and the build then fails somewhere else entirely.
console.log(`gen-privacy-data-list: wrote=${items.length}`);
